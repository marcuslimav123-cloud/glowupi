import { pgTable, serial, text, timestamp, integer, jsonb, boolean, numeric } from "drizzle-orm/pg-core";
import { createInsertSchema } from "drizzle-zod";
import { z } from "zod/v4";
import { usersTable } from "./users";

export const barbeariasTable = pgTable("barbearias", {
  id: serial("id").primaryKey(),
  donoId: integer("dono_id").notNull().references(() => usersTable.id),
  nome: text("nome").notNull(),
  slug: text("slug").notNull().unique(),
  cnpj: text("cnpj"),
  telefone: text("telefone"),
  email: text("email"),
  cep: text("cep"),
  logradouro: text("logradouro"),
  numero: text("numero"),
  bairro: text("bairro"),
  cidade: text("cidade"),
  uf: text("uf"),
  corPrimaria: text("cor_primaria").notNull().default("#3b82f6"),
  logoUrl: text("logo_url"),
  horarioFuncionamento: jsonb("horario_funcionamento"),
  fotos: jsonb("fotos").default([]),
  formasPagamento: jsonb("formas_pagamento").default([]),
  redesSociais: jsonb("redes_sociais").default({}),
  descricaoPublica: text("descricao_publica"),
  planoNome: text("plano_nome").notNull().default("Trial"),
  planoStatus: text("plano_status").notNull().default("ativo"),
  planoVencimento: timestamp("plano_vencimento"),
  stripeCustomerId: text("stripe_customer_id"),
  stripeSubscriptionId: text("stripe_subscription_id"),
  subscriptionStatus: text("subscription_status").default("trial"),
  subscriptionPlan: text("subscription_plan"),
  subscriptionPeriod: text("subscription_period"),
  revenuecatCustomerId: text("revenuecat_customer_id"),
  iapStatus: text("iap_status"),
  iapProductId: text("iap_product_id"),
  iapExpiresAt: timestamp("iap_expires_at"),
  segmentacao: jsonb("segmentacao").default({}),
  onboardingStep: integer("onboarding_step").notNull().default(1),
  tutorialCompleto: boolean("tutorial_completo").notNull().default(false),
  ativo: boolean("ativo").notNull().default(true),
  emailMarketingAtivado: boolean("email_marketing_ativado").notNull().default(false),
  utmSource: text("utm_source"),
  utmMedium: text("utm_medium"),
  utmCampaign: text("utm_campaign"),
  utmContent: text("utm_content"),
  utmTerm: text("utm_term"),
  fbclid: text("fbclid"),
  gclid: text("gclid"),
  landingPage: text("landing_page"),
  referrer: text("referrer"),
  prePagamentoAtivo: boolean("pre_pagamento_ativo").notNull().default(false),
  pixChave: text("pix_chave"),
  pixTitular: text("pix_titular"),
  pixCidade: text("pix_cidade"),
  sinalModo: text("sinal_modo").notNull().default("percentual"),
  sinalValor: numeric("sinal_valor", { precision: 10, scale: 2 }).notNull().default("30"),
  sinalToleranciaMin: integer("sinal_tolerancia_min").notNull().default(30),
  sinalPoliticaTexto: text("sinal_politica_texto"),
  modoHumano: boolean("modo_humano").notNull().default(false),
  createdAt: timestamp("created_at").notNull().defaultNow(),
  updatedAt: timestamp("updated_at").notNull().defaultNow(),
});

export const insertBarbeariaSchema = createInsertSchema(barbeariasTable).omit({
  id: true,
  createdAt: true,
  updatedAt: true,
});

export type InsertBarbearia = z.infer<typeof insertBarbeariaSchema>;
export type Barbearia = typeof barbeariasTable.$inferSelect;
